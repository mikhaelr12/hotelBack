// Utility function to parse query parameters from URL
function getQueryParams() {
    const params = {};
    window.location.search.substring(1).split("&").forEach(pair => {
        const [key, value] = pair.split("=");
        if (key) {
            params[key] = decodeURIComponent(value);
        }
    });
    return params;
}

// Get booking details from query parameters
const params = getQueryParams();
const bookingId = params.bookingId;
const roomId = params.roomId;
const amount = params.amount;

// Display booking information on the page
const bookingInfoDiv = document.getElementById("booking-info");
bookingInfoDiv.innerHTML = `
  <p><strong>Amount:</strong> $${amount}</p>
`;

// Initialize Stripe using the injected publishable key
const stripe = Stripe(stripePublishableKey);
const elements = stripe.elements();

// Create an instance of the card Element with styling.
const style = {
    base: {
        fontSize: "16px",
        color: "#32325d",
        "::placeholder": {
            color: "#aab7c4"
        }
    },
    invalid: {
        color: "#fa755a"
    }
};

const cardElement = elements.create("card", { style: style });
cardElement.mount("#card-element");

const form = document.getElementById("payment-form");
const submitBtn = document.getElementById("submit-btn");
const cardErrors = document.getElementById("card-errors");

form.addEventListener("submit", async function(event) {
    event.preventDefault();
    submitBtn.disabled = true;

    // Create a token using cardElement.
    const { token, error } = await stripe.createToken(cardElement);

    if (error) {
        cardErrors.textContent = error.message;
        submitBtn.disabled = false;
    } else {
        cardErrors.textContent = "";
        const paymentRequest = {
            bookingId: parseInt(bookingId),
            amount: parseFloat(amount),
            source: token.id // Token generated by Stripe
        };

        try {
            const response = await fetch("http://localhost:8080/api/payments/stripe", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify(paymentRequest)
            });

            if (response.ok) {
                const paymentResponse = await response.json();
                alert("Payment successful!");
                window.location.href = '/index';
            } else {
                const errorText = await response.text();
                alert("Payment failed: " + errorText);
            }
        } catch (err) {
            console.error("Error during payment submission:", err);
            alert("An error occurred while processing your payment. Please try again later.");
        } finally {
            submitBtn.disabled = false;
        }
    }
});
